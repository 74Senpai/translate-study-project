-- =========================================================
-- 1. User roles
-- =========================================================
CREATE TABLE IF NOT EXISTS public.user_roles (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(50) NOT NULL UNIQUE,
    details TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =========================================================
-- 2. User profiles
-- id references Supabase Auth user.
-- =========================================================
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    user_name VARCHAR(255) NOT NULL UNIQUE,
    email TEXT NOT NULL,
    display_name TEXT NOT NULL,
    avatar_url TEXT,
    role_id BIGINT REFERENCES public.user_roles(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =========================================================
-- 3. Repetition schedule definitions
-- =========================================================
CREATE TABLE IF NOT EXISTS public.repetition_loops (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    loop_order INTEGER NOT NULL UNIQUE
        CHECK (loop_order >= 0),
    day_repetition INTEGER NOT NULL
        CHECK (day_repetition >= 0),
    pre_loop_id INTEGER
        REFERENCES public.repetition_loops(id) ON DELETE SET NULL,
    next_loop_id INTEGER
        REFERENCES public.repetition_loops(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CHECK (pre_loop_id IS NULL OR pre_loop_id <> id),
    CHECK (next_loop_id IS NULL OR next_loop_id <> id)
);


-- =========================================================
-- 4. Lexical entries (lemmas)
-- =========================================================
CREATE TABLE IF NOT EXISTS public.words (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    word_text VARCHAR(255) NOT NULL,
    is_validated BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    validated_at TIMESTAMPTZ,

    CONSTRAINT words_word_text_unique UNIQUE (word_text)
);

CREATE INDEX IF NOT EXISTS idx_words_word_text_lower
    ON public.words (LOWER(word_text));


-- =========================================================
-- 5. Senses
-- id is a STRING generated by the application/system.
-- =========================================================
CREATE TABLE IF NOT EXISTS public.senses (
    id TEXT PRIMARY KEY,
    word_id UUID NOT NULL
        REFERENCES public.words(id) ON DELETE CASCADE,
    meaning_vi VARCHAR(255) NOT NULL,
    definition_en TEXT,
    definition_vi TEXT,
    example_en TEXT,
    example_vi TEXT,
    synonyms TEXT[] NOT NULL DEFAULT '{}',
    antonyms TEXT[] NOT NULL DEFAULT '{}',
    match_count INTEGER NOT NULL DEFAULT 0
        CHECK (match_count >= 0),
    confidence_score REAL NOT NULL DEFAULT 0
        CHECK (
            confidence_score >= 0
            AND confidence_score <= 1
        ),
    is_trusted BOOLEAN NOT NULL DEFAULT FALSE,
    rating_count INTEGER NOT NULL DEFAULT 0
        CHECK (rating_count >= 0),
    rating_score REAL NOT NULL DEFAULT 0
        CHECK (rating_score >= 0),
    part_of_speech VARCHAR(50),
    ipa VARCHAR(255),
    audio_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_senses_word_id
    ON public.senses(word_id);

CREATE INDEX IF NOT EXISTS idx_senses_meaning_vi
    ON public.senses(meaning_vi);

CREATE INDEX IF NOT EXISTS idx_senses_part_of_speech
    ON public.senses(part_of_speech);


-- =========================================================
-- 6. Optional inflected/variant forms
-- Example: runs/running/ran -> run
-- =========================================================
CREATE TABLE IF NOT EXISTS public.word_forms (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    word_id UUID NOT NULL
        REFERENCES public.words(id) ON DELETE CASCADE,
    form_text VARCHAR(255) NOT NULL,
    form_type VARCHAR(50),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (word_id, form_text)
);

CREATE INDEX IF NOT EXISTS idx_word_forms_form_text_lower
    ON public.word_forms (LOWER(form_text));


-- =========================================================
-- 7. User progress per sense
-- sense_id is TEXT to match senses.id.
-- =========================================================
CREATE TABLE IF NOT EXISTS public.user_sense_progress (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL
        REFERENCES public.profiles(id) ON DELETE CASCADE,
    sense_id TEXT NOT NULL
        REFERENCES public.senses(id) ON DELETE CASCADE,
    mastery_score REAL NOT NULL DEFAULT 0
        CHECK (mastery_score >= 0),
    translated_count INTEGER NOT NULL DEFAULT 0
        CHECK (translated_count >= 0),
    last_translated TIMESTAMPTZ,
    last_review TIMESTAMPTZ,
    current_repetition_id INTEGER
        REFERENCES public.repetition_loops(id) ON DELETE SET NULL,
    next_review TIMESTAMPTZ,
    wrong_count INTEGER NOT NULL DEFAULT 0
        CHECK (wrong_count >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (user_id, sense_id)
);

CREATE INDEX IF NOT EXISTS idx_user_sense_progress_user_id
    ON public.user_sense_progress(user_id);

CREATE INDEX IF NOT EXISTS idx_user_sense_progress_sense_id
    ON public.user_sense_progress(sense_id);

CREATE INDEX IF NOT EXISTS idx_user_sense_progress_due
    ON public.user_sense_progress(user_id, next_review)
    WHERE next_review IS NOT NULL;


-- =========================================================
-- 8. Optional word-level exposure/history
-- =========================================================
CREATE TABLE IF NOT EXISTS public.user_words (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL
        REFERENCES public.profiles(id) ON DELETE CASCADE,
    word_id UUID NOT NULL
        REFERENCES public.words(id) ON DELETE CASCADE,
    translated_count INTEGER NOT NULL DEFAULT 0
        CHECK (translated_count >= 0),
    last_translated TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (user_id, word_id)
);

CREATE INDEX IF NOT EXISTS idx_user_words_user_id
    ON public.user_words(user_id);

CREATE INDEX IF NOT EXISTS idx_user_words_word_id
    ON public.user_words(word_id);


-- =========================================================
-- 9. User-provided notes/context for a sense
-- sense_id is TEXT to match senses.id.
-- =========================================================
CREATE TABLE IF NOT EXISTS public.user_sense_notes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL
        REFERENCES public.profiles(id) ON DELETE CASCADE,
    sense_id TEXT NOT NULL
        REFERENCES public.senses(id) ON DELETE CASCADE,
    meaning_note TEXT,
    context TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_user_sense_notes_user_sense
    ON public.user_sense_notes(user_id, sense_id);


-- =========================================================
-- 10. Statistics per sense
-- Separate statistics by interaction type.
-- =========================================================
CREATE TABLE IF NOT EXISTS public.user_sense_stats (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL
        REFERENCES public.profiles(id) ON DELETE CASCADE,
    sense_id TEXT NOT NULL
        REFERENCES public.senses(id) ON DELETE CASCADE,
    hard_score REAL NOT NULL DEFAULT 0,
    choose_fail_count INTEGER NOT NULL DEFAULT 0
        CHECK (choose_fail_count >= 0),
    choose_true_count INTEGER NOT NULL DEFAULT 0
        CHECK (choose_true_count >= 0),
    fill_fail_count INTEGER NOT NULL DEFAULT 0
        CHECK (fill_fail_count >= 0),
    fill_true_count INTEGER NOT NULL DEFAULT 0
        CHECK (fill_true_count >= 0),
    write_fail_count INTEGER NOT NULL DEFAULT 0
        CHECK (write_fail_count >= 0),
    write_true_count INTEGER NOT NULL DEFAULT 0
        CHECK (write_true_count >= 0),
    listen_fail_count INTEGER NOT NULL DEFAULT 0
        CHECK (listen_fail_count >= 0),
    listen_true_count INTEGER NOT NULL DEFAULT 0
        CHECK (listen_true_count >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (user_id, sense_id)
);

CREATE INDEX IF NOT EXISTS idx_user_sense_stats_user_id
    ON public.user_sense_stats(user_id);

CREATE INDEX IF NOT EXISTS idx_user_sense_stats_sense_id
    ON public.user_sense_stats(sense_id);


-- =========================================================
-- 11. Optional aggregate/cache stats per user
-- =========================================================
CREATE TABLE IF NOT EXISTS public.user_stats (
    user_id UUID PRIMARY KEY
        REFERENCES public.profiles(id) ON DELETE CASCADE,
    total_word_match INTEGER NOT NULL DEFAULT 0
        CHECK (total_word_match >= 0),
    total_sense_match INTEGER NOT NULL DEFAULT 0
        CHECK (total_sense_match >= 0),
    last_translated TIMESTAMPTZ,
    last_review TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =========================================================
-- 12. Optional detailed answer/attempt history
-- sense_id is TEXT to match senses.id.
-- =========================================================
CREATE TABLE IF NOT EXISTS public.user_sense_attempts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL
        REFERENCES public.profiles(id) ON DELETE CASCADE,
    sense_id TEXT NOT NULL
        REFERENCES public.senses(id) ON DELETE CASCADE,
    activity_type VARCHAR(20) NOT NULL
        CHECK (
            activity_type IN (
                'choose',
                'fill',
                'write',
                'listen',
                'translate'
            )
        ),
    is_correct BOOLEAN NOT NULL,
    user_answer TEXT,
    context TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_user_sense_attempts_user_created
    ON public.user_sense_attempts(user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_user_sense_attempts_sense_created
    ON public.user_sense_attempts(sense_id, created_at DESC);